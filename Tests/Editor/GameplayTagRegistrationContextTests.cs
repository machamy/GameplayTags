using System.Collections.Generic;
using System.Linq;
using NUnit.Framework;
using Machamy.GameplayTags.Runtime;

namespace Machamy.GameplayTags.Tests
{
    /// <summary>
    /// 태그 중복 등록 정책 테스트.
    /// Resources.LoadAll이 같은 데이터베이스의 복제 인스턴스를 여러 번 돌려주는 환경(배치모드, 테스트 러너)에서도
    /// 정의가 동일하다면 에러 없이 한 번만 등록되어야 합니다.
    /// </summary>
    public class GameplayTagRegistrationContextTests
    {
        private sealed class FakeSource : IGameplayTagSource
        {
            public FakeSource(string name) => Name = name;

            public string Name { get; }

            public void RegisterTags(GameplayTagRegistrationContext context)
            {
            }
        }

        [Test]
        public void Test_IdenticalDuplicate_IsIgnoredWithoutError()
        {
            var context = new GameplayTagRegistrationContext();
            var source = new FakeSource("Fake");

            // 같은 데이터베이스가 3번 로드된 상황
            for (int i = 0; i < 3; i++)
            {
                context.RegisterTag("State.Player.Oxygen", "산소 상태", source);
            }

            CollectionAssert.IsEmpty(context.GetRegistrationErrors(),
                "동일한 정의의 중복 등록은 에러가 아니어야 합니다.");

            List<GameplayTagSpec> definitions = context.GenerateDefinitions();
            Assert.AreEqual(1, definitions.Count(definition => definition.TagName == "State.Player.Oxygen"),
                "중복 등록된 태그는 하나의 정의만 생성되어야 합니다.");
        }

        [Test]
        public void Test_ConflictingDescription_ReportsError()
        {
            var context = new GameplayTagRegistrationContext();

            context.RegisterTag("State.Player.Oxygen", "산소 상태", new FakeSource("A"));
            context.RegisterTag("State.Player.Oxygen", "전혀 다른 설명", new FakeSource("B"));

            List<GameplayTagRegistrationError> errors = context.GetRegistrationErrors().ToList();
            Assert.AreEqual(1, errors.Count, "설명이 서로 다른 중복 등록은 에러로 보고되어야 합니다.");
            Assert.AreEqual("State.Player.Oxygen", errors[0].TagName);
        }

        [Test]
        public void Test_EmptyDescription_DoesNotConflict()
        {
            var context = new GameplayTagRegistrationContext();

            context.RegisterTag("State.Player.Oxygen", "", new FakeSource("A"));
            context.RegisterTag("State.Player.Oxygen", "산소 상태", new FakeSource("B"));

            CollectionAssert.IsEmpty(context.GetRegistrationErrors(),
                "한쪽 설명이 비어있는 것은 정의 충돌이 아닙니다.");

            GameplayTagSpec definition = context.GenerateDefinitions()
                .Single(candidate => candidate.TagName == "State.Player.Oxygen");
            Assert.AreEqual("산소 상태", definition.Description,
                "비어있지 않은 설명이 채택되어야 합니다.");
        }

        [Test]
        public void Test_AutoGeneratedParent_IsReplacedByRealDefinition()
        {
            var context = new GameplayTagRegistrationContext();
            var source = new FakeSource("Fake");

            // "State", "State.Player"가 자동 생성됨
            context.RegisterTag("State.Player.Oxygen", "산소 상태", source);
            // 이후 실제 정의가 들어옴
            context.RegisterTag("State.Player", "플레이어 상태", source);

            CollectionAssert.IsEmpty(context.GetRegistrationErrors(),
                "자동 생성된 부모 태그를 실제 정의로 대체하는 것은 에러가 아닙니다.");

            GameplayTagSpec parent = context.GenerateDefinitions()
                .Single(candidate => candidate.TagName == "State.Player");
            Assert.AreEqual("플레이어 상태", parent.Description);
            Assert.AreSame(source, parent.Source);
        }
    }
}
